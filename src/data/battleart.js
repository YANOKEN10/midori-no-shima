const cache = new Map();
for (const name of Object.keys(FILES)) {
  const img = new Image();
  img.decoding = "async";
  img.src = new URL(FILES[name], import.meta.url).href;
  cache.set(name, img);
}

export function battleArt(name) {
  const img = cache.get(name);
  return img && img.complete && img.naturalWidth ? img : null;
}

