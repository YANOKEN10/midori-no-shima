export const TYPES = ["ノーマル", "くさ", "ほのお", "みず", "でんき", "じめん", "むし", "やみ"];

// こうげき側 → まもり側 の ばいりつ（かいてないものは 1）
const CHART = {
  ノーマル: { やみ: 0.5 },
  くさ: { みず: 2, じめん: 2, ほのお: 0.5, くさ: 0.5, むし: 0.5 },
  ほのお: { くさ: 2, むし: 2, ほのお: 0.5, みず: 0.5 },
  みず: { ほのお: 2, じめん: 2, みず: 0.5, くさ: 0.5 },
  でんき: { みず: 2, くさ: 0.5, でんき: 0.5, じめん: 0 },
  じめん: { ほのお: 2, でんき: 2, くさ: 0.5, むし: 0.5 },
  むし: { くさ: 2, やみ: 2, ほのお: 0.5 },
  やみ: { ノーマル: 2, むし: 0.5 },
};

export function effect(atkType, defTypes) {
  let m = 1;
  const row = CHART[atkType] || {};
  for (const d of defTypes) {
    if (row[d] != null) m *= row[d];
  }
  return m;
}

export function effectWord(m) {
  if (m === 0) return "こうかが ないようだ…";
  if (m >= 2) return "こうかは バツグンだ！";
  if (m < 1) return "こうかは いまひとつの ようだ…";
  return "";
}
